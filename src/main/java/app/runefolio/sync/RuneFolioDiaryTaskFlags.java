    static boolean observes(int varp, int varbit)
    {
        for (Tier tier : TIERS)
        {
            for (Flag flag : tier.flags)
            {
                if (flag.varbit ? flag.id == varbit : flag.id == varp) return true;
            }
        }
        return false;
    }

    static JsonArray collect(Client client, JsonArray counts)
    {
        return collect(client::getVarpValue, client::getVarbitValue, counts);
    }

    // Only publish an area's identities when all four tiers agree with the game's
    // independent counters. A changed mapping or unready client stays unknown.
    static JsonArray collect(IntUnaryOperator varps, IntUnaryOperator varbits, JsonArray counts)
    {
        JsonArray areas = new JsonArray();
        for (int offset = 0; offset < TIERS.length; offset += 4)
        {
            JsonArray tiers = new JsonArray();
            boolean valid = true;
            for (int index = offset; index < offset + 4; index++)
            {
                Tier mapping = TIERS[index];
                JsonArray completed = new JsonArray();
                for (int task = 0; task < mapping.flags.length; task++)
                {
                    Flag flag = mapping.flags[task];
                    int value = (flag.varbit ? varbits : varps).applyAsInt(flag.id);
                    if (flag.varbit ? value >= flag.position : ((value >>> flag.position) & 1) != 0)
                    {
                        completed.add(task + 1);
                    }
                }
                JsonObject count = findCount(counts, mapping.area, mapping.tier);
                if (count == null || count.get("totalCount").getAsInt() != mapping.flags.length
                    || count.get("completedCount").getAsInt() != completed.size())
                {
                    valid = false;
                    break;
                }
                JsonObject tier = new JsonObject();
                tier.addProperty("tier", mapping.tier);
                tier.add("completedTaskIndices", completed);
                tiers.add(tier);
            }
            if (valid)
            {
                JsonObject area = new JsonObject();
                area.addProperty("area", TIERS[offset].area);
                area.addProperty("taskMappingRevision", REVISION);
                area.add("tiers", tiers);
                areas.add(area);
            }
        }
        return areas;
    }

    private static JsonObject findCount(JsonArray counts, String area, String tier)
    {
        for (JsonElement value : counts)
        {
            JsonObject candidate = value.getAsJsonObject();
            if (!area.equals(candidate.get("area").getAsString())) continue;
            for (JsonElement entry : candidate.getAsJsonArray("tiers"))
            {
                JsonObject result = entry.getAsJsonObject();
                if (tier.equals(result.get("tier").getAsString())) return result;
            }
        }
        return null;
    }

    private static final class Tier
    {
        final String area;
        final String tier;
        final Flag[] flags;
        Tier(String area, String tier, Flag[] flags)
        {
            this.area = area;
            this.tier = tier;
            this.flags = flags;
        }
    }

    private static final class Flag
    {
        final boolean varbit;
        final int id;
        // Zero-based bit position for varps; minimum completed value for varbits.
        final int position;
        Flag(boolean varbit, int id, int position)
        {
            this.varbit = varbit;
            this.id = id;
            this.position = position;
        }
    }
